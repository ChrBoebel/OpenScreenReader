@MainActor
final class GenerationGate {
  private var current: UUID?
  func begin() -> UUID {
    let id = UUID()
    current = id
    return id
  }
  func cancel() { current = nil }
  func accepts(_ id: UUID) -> Bool { current == id }
}
/// The pasteboard operations dictation uses: `NSPasteboard` in the app, a recorder in tests.
protocol DictationPasteboard: AnyObject {
  var changeCount: Int { get }
  var pasteboardItems: [NSPasteboardItem]? { get }
  @discardableResult func prepareForNewContents(with options: NSPasteboard.ContentsOptions) -> Int
  func writeObjects(_ objects: [any NSPasteboardWriting]) -> Bool
  func string(forType dataType: NSPasteboard.PasteboardType) -> String?
}
extension NSPasteboard: DictationPasteboard {}

/// nspasteboard.org markers that clipboard managers and password managers honour.
enum PasteboardMarker {
  static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
  static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
  static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
  static let all: Set<String> = [concealed.rawValue, transient.rawValue, autoGenerated.rawValue]
}

@MainActor
struct ClipboardSnapshot: Equatable {
  let items: [[String: Data]]
  /// Promised files are produced on demand by their source app and cannot be copied safely.
  private static let promiseTypes: Set<String> = [
    "com.apple.NSFilePromiseItemMetaData", "com.apple.pasteboard.promised-file-url",
    "com.apple.pasteboard.promised-file-content-type", "com.apple.pasteboard.promised-suggested-file-name",
    "Apple files promise pasteboard type",
  ]
  /// Marked by a password manager or as transient/generated content; such data is never put back.
  var isMarkedPrivate: Bool { items.contains { !PasteboardMarker.all.isDisjoint(with: $0.keys) } }

  static func capture(_ board: any DictationPasteboard, limit: Int = 16 * 1024 * 1024) throws -> Self {
    let count = board.changeCount
    var size = 0
    var result = [[String: Data]]()
    for item in board.pasteboardItems ?? [] {
      // Decide from the type list alone before asking any app to produce data.
      guard Self.promiseTypes.isDisjoint(with: item.types.map(\.rawValue)) else {
        throw DictationError(
          String(localized: "The clipboard holds data that cannot be restored safely. Copy the result manually.")
        )
      }
      var types = [String: Data]()
      for type in item.types {
        guard let data = item.data(forType: type) else {
          throw DictationError(
            String(localized: "The clipboard holds data that cannot be restored safely. Copy the result manually.")
          )
        }
        size += data.count
        guard size <= limit else {
          throw DictationError(
            String(localized: "The clipboard is larger than 16 MB. It stays unchanged; copy the result manually.")
          )
        }
        types[type.rawValue] = data
      }
      result.append(types)
    }
    guard board.changeCount == count else {
      throw DictationError(String(localized: "The clipboard changed. Please try again."))
    }
    return Self(items: result)
  }
  /// Restored data stays on this Mac and never reaches Universal Clipboard.
  func write(to board: any DictationPasteboard) -> Bool {
    let objects = items.map { types -> NSPasteboardItem in
      let item = NSPasteboardItem()
      for (type, data) in types { item.setData(data, forType: .init(type)) }
      return item
    }
    board.prepareForNewContents(with: .currentHostOnly)
    return objects.isEmpty || board.writeObjects(objects)
  }
}
@MainActor
final class ClipboardLease {
  private let board: any DictationPasteboard
  private var original: ClipboardSnapshot?
  private let ownedCount: Int
  private let marker: String
  private static let markerType = NSPasteboard.PasteboardType("local.qwen.dictation.transient")
  /// A password manager's item is cleared rather than restored: putting it back would look like a
  /// new copy and stop the manager's own timed clearing.
  let clearsInsteadOfRestoring: Bool
  private init(board: any DictationPasteboard, original: ClipboardSnapshot, ownedCount: Int, marker: String) {
    self.board = board
    self.original = original
    self.ownedCount = ownedCount
    self.marker = marker
    clearsInsteadOfRestoring = original.isMarkedPrivate
  }
  static func begin(_ text: String, on board: any DictationPasteboard) throws -> ClipboardLease {
    let count = board.changeCount
    let original = try ClipboardSnapshot.capture(board)
    let marker = UUID().uuidString
    let item = NSPasteboardItem()
    item.setString(text, forType: .string)
    item.setString(marker, forType: markerType)
    // Clipboard managers skip these items, and the transcript never syncs to other devices.
    for type in [PasteboardMarker.concealed, PasteboardMarker.transient, PasteboardMarker.autoGenerated] {
      item.setData(Data(), forType: type)
    }
    guard board.changeCount == count else {
      throw DictationError(String(localized: "The clipboard changed while pasting was prepared."))
    }
    board.prepareForNewContents(with: .currentHostOnly)
    guard board.writeObjects([item]) else {
      _ = original.isMarkedPrivate ? ClipboardSnapshot(items: []).write(to: board) : original.write(to: board)
      throw DictationError(String(localized: "The clipboard could not be prepared."))
    }
    return ClipboardLease(
      board: board, original: original, ownedCount: board.changeCount, marker: marker)
  }
  /// Restores, or for private items clears, only while the transcript is still ours; newer copies win.
  @discardableResult func restore() -> Bool {
    guard let saved = original else { return false }
    original = nil
    guard board.changeCount == ownedCount, board.string(forType: Self.markerType) == marker else {
      return false
    }
    return (clearsInsteadOfRestoring ? ClipboardSnapshot(items: []) : saved).write(to: board)
  }
}
struct AudioPacket: Sendable {
  let samples: [Float]
  let rate: Double
}
final class AudioAccumulator: @unchecked Sendable {
  private let lock = NSLock()
  private var samples = [Float]()
  private var rate = 16000.0
  private var active = false
  private var level: Double = 0
  func start(sampleRate: Double) {
    lock.lock()
    defer { lock.unlock() }
    samples = []
    rate = sampleRate
    active = true
    level = 0
  }
  func append(_ chunk: [Float]) {
    lock.lock()
    defer { lock.unlock() }
    guard active else { return }
    let remaining = max(0, Int(rate * 60) - samples.count)
    samples.append(contentsOf: chunk.prefix(remaining))
    level = chunk.isEmpty ? 0 : sqrt(chunk.reduce(0) { $0 + Double($1 * $1) } / Double(chunk.count))
  }
  var rms: Double {
    lock.lock()
    defer { lock.unlock() }
    return level
  }
  func finish() -> AudioPacket {
    lock.lock()
    defer { lock.unlock() }
    active = false
    let out = AudioPacket(samples: samples, rate: rate)
    samples = []
    level = 0
    return out
  }
  func cancel() {
    lock.lock()
    defer { lock.unlock() }
    active = false
    samples = []
    level = 0
  }
}
